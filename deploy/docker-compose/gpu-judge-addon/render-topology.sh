#!/bin/bash
# 由 runtime.env 生成多实例拓扑：compose.instances.yml（每卡 N 个 llama-server 实例）
# 与 nginx/nginx.conf（TLS 终结 + least_conn 负载均衡）。install.sh 调用；无 GPU 也可运行，便于测试。
# 用法：render-topology.sh <runtime.env> <输出目录>
set -Eeuo pipefail
umask 077

ENV_FILE="$1"
OUT="$2"
IMAGE="${GPU_JUDGE_IMAGE:-jjdguard/llm-judge-gpu:2.1.0}"
fail() { echo "[error] $*" >&2; exit 1; }
valid_uint() { [[ "$1" =~ ^[0-9]+$ ]] && (( 10#$1 >= $2 && 10#$1 <= $3 )); }
read_env() {
  local key="$1" count
  count="$(grep -c "^${key}=" "$ENV_FILE" || true)"
  [[ "$count" == 1 ]] || fail "runtime.env must contain exactly one $key"
  sed -n "s/^${key}=//p" "$ENV_FILE"
}

[[ -f "$ENV_FILE" && ! -L "$ENV_FILE" ]] || fail 'runtime.env is missing'
[[ -d "$OUT" && ! -L "$OUT" ]] || fail 'output directory is missing'
GPU_IDS="$(read_env JUDGE_GPU_IDS)"
PER_GPU="$(read_env JUDGE_INSTANCES_PER_GPU)"
PARALLEL="$(read_env JUDGE_PARALLEL)"
CTX="$(read_env JUDGE_CTX)"
[[ "$GPU_IDS" =~ ^[0-9]{1,2}(,[0-9]{1,2}){0,15}$ ]] || fail 'JUDGE_GPU_IDS must be a comma-separated list of GPU indexes, e.g. 0,1'
valid_uint "$PER_GPU" 1 8 || fail 'JUDGE_INSTANCES_PER_GPU must be between 1 and 8'
valid_uint "$PARALLEL" 1 32 || fail 'JUDGE_PARALLEL must be between 1 and 32'
valid_uint "$CTX" 2048 262144 || fail 'JUDGE_CTX must be between 2048 and 262144'
(( 10#$CTX / 10#$PARALLEL >= 8192 )) || fail 'JUDGE_CTX / JUDGE_PARALLEL must leave at least 8192 tokens per slot'

IFS=',' read -ra gpus <<<"$GPU_IDS"
declare -A seen=()
for g in "${gpus[@]}"; do
  [[ -z "${seen[$g]+x}" ]] || fail "JUDGE_GPU_IDS lists GPU $g twice"
  seen[$g]=1
done

compose_tmp="$(mktemp "$OUT/.compose.instances.XXXXXX")"
upstream=""
services=()
{
  printf '# Generated by render-topology.sh from runtime.env; do not edit by hand.\n'
  printf 'services:\n'
  for g in "${gpus[@]}"; do
    for ((i = 0; i < 10#$PER_GPU; i++)); do
      name="judge-g${g}-i${i}"
      services+=("$name")
      upstream+="    server ${name}:8080 max_fails=2 fail_timeout=10s;"$'\n'
      cat <<EOF
  ${name}:
    image: ${IMAGE}
    restart: unless-stopped
    env_file:
      - runtime.env
    environment:
      JUDGE_MODEL_PATH: /models/jjdguard-bundled-judge-4b-v1-Q4_K_M.gguf
      JUDGE_ALIAS: bundled-judge
      NVIDIA_VISIBLE_DEVICES: "${g}"
      NVIDIA_DRIVER_CAPABILITIES: compute,utility
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              device_ids: ["${g}"]
              capabilities: [gpu]
    networks:
      - judge-backend
    volumes:
      - ./models:/models:ro
    read_only: true
    tmpfs:
      - /tmp:rw,noexec,nosuid,size=256m
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
    healthcheck:
      # /health 只在模型加载完成后返回 200；nginx 只把流量给健康实例（depends_on + max_fails）。
      test: ["CMD", "/usr/local/bin/jjdguard-gpu-judge-health"]
      interval: 10s
      timeout: 3s
      retries: 18
      start_period: 90s
EOF
    done
  done
  printf '  judge-lb:\n    depends_on:\n'
  for name in "${services[@]}"; do
    printf '      %s:\n        condition: service_healthy\n' "$name"
  done
} >"$compose_tmp"

mkdir -p "$OUT/nginx"
nginx_tmp="$(mktemp "$OUT/nginx/.nginx.conf.XXXXXX")"
cat >"$nginx_tmp" <<EOF
# Generated by render-topology.sh from runtime.env; do not edit by hand.
worker_processes auto;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;
events { worker_connections 4096; }
http {
  access_log off;
  server_tokens off;
  client_body_temp_path /tmp/client_body;
  proxy_temp_path /tmp/proxy;
  fastcgi_temp_path /tmp/fastcgi;
  uwsgi_temp_path /tmp/uwsgi;
  scgi_temp_path /tmp/scgi;
  client_max_body_size 4m;
  upstream judge_backends {
    # 共享内存区：没有 zone 时每个 worker 各自计数，least_conn 会把请求全压到第一个实例。
    zone judge_backends 1m;
    least_conn;
${upstream}    keepalive 64;
  }
  server {
    listen 8443 ssl;
    http2 on;
    ssl_certificate /tls/server.crt;
    ssl_certificate_key /tls/server.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:judge_tls:10m;
    location = /lb-health { return 200 "ok\n"; }
    location / {
      proxy_pass http://judge_backends;
      proxy_http_version 1.1;
      proxy_set_header Connection "";
      proxy_set_header Host \$host;
      proxy_connect_timeout 2s;
      proxy_read_timeout 120s;
      proxy_send_timeout 30s;
      # 只在连接失败/实例 5xx 时换实例；超时不重试，避免把慢请求放大成多份算力。
      proxy_next_upstream error http_502 http_503;
      proxy_next_upstream_tries 2;
      proxy_buffering off;
    }
  }
}
EOF
chmod 0644 "$compose_tmp" "$nginx_tmp"
mv -f "$compose_tmp" "$OUT/compose.instances.yml"
mv -f "$nginx_tmp" "$OUT/nginx/nginx.conf"
echo "[ok] topology: gpus=${GPU_IDS} instances_per_gpu=${PER_GPU} backends=${#services[@]} parallel=${PARALLEL} ctx=${CTX}"
