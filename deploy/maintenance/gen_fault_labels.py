#!/usr/bin/env python3
"""Generate the Go runtime-fault label table by lifting CJK verbatim from the
authoritative sources, never by hand.

Sources:
  * apps/web-console/src/utils/alertInboxDisplay.ts  -> the per-reason operator labels
    and the unknown-reason fallback already shipped in the console.
  * apps/control-plane/internal/alert/secevent_bridge.go -> the existing
    "检测运行故障" display label.

Hand-typing CJK silently produces homoglyph defects, so every character written
into the generated Go file is copied out of an existing file byte-for-byte. The
script also prints the codepoints it extracted so the result can be checked.
"""
import pathlib
import re
import shutil
import subprocess
import sys

def resolve_root():
    here = pathlib.Path(__file__).resolve()
    for candidate in list(here.parents) + [pathlib.Path.cwd()]:
        if (candidate / "apps" / "web-console").is_dir() and (candidate / "apps" / "control-plane").is_dir():
            return candidate
    raise SystemExit("run this from the product repo root")


ROOT = resolve_root()

INBOX = ROOT / "apps/web-console/src/utils/alertInboxDisplay.ts"
BRIDGE = ROOT / "apps/control-plane/internal/alert/secevent_bridge.go"
OUT = ROOT / "apps/control-plane/internal/alert/fault_grouping.go"


def lift_reason_labels(text):
    match = re.search(r"const reasons: Record<string, string> = \{(.*?)\}\n", text, re.S)
    if not match:
        raise SystemExit("reason label map not found in alertInboxDisplay.ts")
    body = match.group(1)
    pairs = re.findall(r"([A-Za-z_][A-Za-z0-9_]*)\s*:\s*'([^']*)'", body)
    if len(pairs) < 8:
        raise SystemExit("only %d reason labels parsed; the console map changed shape" % len(pairs))
    return pairs


def lift_fallback(text):
    match = re.search(r"detail = reasons\[reason\] \|\| '([^']*)'", text)
    if not match:
        raise SystemExit("fallback label not found in alertInboxDisplay.ts")
    return match.group(1)


def lift_fault_title(text, needle):
    """Find the console's runtime-fault title by anchoring on the label already
    lifted from the Go source, so no CJK is hand-typed here. The console writes
    the title as a template literal that starts with the class label and then
    appends the disposition, either inline or through actionSuffix(...)."""
    if not re.search(re.escape("`" + needle) + r"(?: · |\$\{)", text):
        raise SystemExit(
            "console has no runtime_fault title starting with %r; the two sides "
            "describe the fault class differently" % needle
        )
    return needle


def lift_event_display_label(text):
    match = re.search(r'return "([^"]*)"\n\t}\n\tif alertTypeForSecurityEvent\(ev\) == "access_governance"', text)
    if not match:
        raise SystemExit('"检测运行故障" display label not found in secevent_bridge.go')
    return match.group(1)


def go_string(value):
    # Go string literal: the lifted text is CJK plus ASCII, no quoting hazards,
    # but escape defensively and keep the bytes exactly as lifted.
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped + '"'


def main():
    inbox = INBOX.read_text(encoding="utf-8")
    bridge = BRIDGE.read_text(encoding="utf-8")

    pairs = lift_reason_labels(inbox)
    fallback = lift_fallback(inbox)
    display_label = lift_event_display_label(bridge)
    fault_title = lift_fault_title(inbox, display_label)

    lines = []
    lines.append("package alert\n")
    lines.append("// Code generated by deploy/maintenance/gen_fault_labels.py; DO NOT EDIT.")
    lines.append("//")
    lines.append("// Every Chinese word here is lifted byte-for-byte from")
    lines.append("// apps/web-console/src/utils/alertInboxDisplay.ts and secevent_bridge.go: the fault")
    lines.append("// class label, the ten reason labels, and the unknown-reason fallback.")
    lines.append("//")
    lines.append("// The two sides assemble those words differently on purpose. The console titles")
    lines.append("// a fault group with the class label and the disposition, and renders the reason")
    lines.append("// in its detail line; a DingTalk/mail/webhook card has no detail line, so the")
    lines.append("// title built here carries the reason and the pipeline stage instead. What must")
    lines.append("// hold is the shared vocabulary, and TestFaultReasonLabelsMatchTheConsole")
    lines.append("// re-reads the console on every run to enforce it; regenerate with:")
    lines.append("//")
    lines.append("//	python3 deploy/maintenance/gen_fault_labels.py")
    lines.append("")
    lines.append("// faultDisplayLabelCN is the human label for the whole runtime-fault class.")
    lines.append("const faultDisplayLabelCN = " + go_string(fault_title))
    lines.append("")
    lines.append("// faultUnknownReasonLabelCN is shown when the engine reports a reason this")
    lines.append("// build does not know: never leak the raw English enum to a customer.")
    lines.append("const faultUnknownReasonLabelCN = " + go_string(fallback))
    lines.append("")
    lines.append("// faultStageParenOpen / faultStageParenClose wrap the pipeline stage in the")
    lines.append("// fault title. They are written as escapes so the Go source stays ASCII and a")
    lines.append("// reviewer never has to judge whether two lookalike glyphs differ.")
    lines.append('const faultStageParenOpen = "\\uFF08"  // fullwidth left parenthesis')
    lines.append('const faultStageParenClose = "\\uFF09" // fullwidth right parenthesis')
    lines.append("")
    lines.append("// faultReasonLabelCN maps engine semantic_reason / inspection_reason values")
    lines.append("// to operator-visible Chinese. Keys are the engine contract.")
    lines.append("var faultReasonLabelCN = map[string]string{")
    # gofmt aligns the value column of a contiguous composite literal, so build
    # the exact bytes it would produce: pad "key": to the widest key, then one
    # space before the value. Anything else leaves the file gofmt-dirty.
    keys = [go_string(key) + ":" for key, _ in pairs]
    pad = max(len(k) for k in keys)
    for key, value in pairs:
        lines.append("\t" + (go_string(key) + ":").ljust(pad) + " " + go_string(value) + ",")
    lines.append("}\n")
    lines.append("// faultReasonLabel returns the Chinese label for an engine reason, or the")
    lines.append("// neutral fallback when the reason is empty or unrecognised.")
    lines.append("func faultReasonLabel(reason string) string {")
    lines.append("\tif label, ok := faultReasonLabelCN[reason]; ok {")
    lines.append("\t\treturn label")
    lines.append("\t}")
    lines.append("\treturn faultUnknownReasonLabelCN")
    lines.append("}")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    gofmt = shutil.which("gofmt") or shutil.which("gofmt", path="/usr/local/go/bin")
    if not gofmt:
        raise SystemExit("gofmt not found; refusing to emit output that may be unformatted")
    check = subprocess.run([gofmt, "-l", str(OUT)], capture_output=True, text=True)
    if check.stdout.strip():
        raise SystemExit("generated file is not gofmt-clean: %s" % check.stdout.strip())

    print("wrote %s (gofmt clean)" % OUT)
    print("fault_title=%s" % fault_title)
    print("fallback=%s" % fallback)
    print("reasons=%d" % len(pairs))
    for key, value in pairs:
        print("  %-34s %s" % (key, value))
    for label in [fault_title, fallback] + [v for _, v in pairs]:
        weird = [c for c in label if ord(c) > 127 and not (
            0x4E00 <= ord(c) <= 0x9FFF or 0x3000 <= ord(c) <= 0x303F
            or 0xFF00 <= ord(c) <= 0xFFEF or ord(c) in (0x2018, 0x2019, 0x201C, 0x201D, 0x2014)
        )]
        if weird:
            raise SystemExit("unexpected non-CJK char in %r: %s" % (label, weird))


if __name__ == "__main__":
    sys.exit(main())
